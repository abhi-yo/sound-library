// Shared helpers for the /browse anatomy figures (06–09).
// Geometry is built once here with the anatomy kit and written to
// components/frontends/browse/anatomy/*.art.ts as finished SVG strings.
import { writeFileSync } from "node:fs";
import * as k from "./kit/iso-kit.mjs";
import * as G from "./kit/lathe.mjs";

export { k, G };

/** Front-elevation camera: square to the viewer, a little above the bench. */
export const EL = 16;

export function camOf(P) {
  const c = k.cameraOf(P);
  return { ox: P.origin[0], oy: P.origin[1], sinA: c.sinA, cosA: c.cosA, sinE: c.sinE, cosE: c.cosE, k: c.k };
}

export const r2 = (v) => Math.round(v * 100) / 100;

/** A flat polygon in 3D, shaded by facing like the kit's prisms. */
export function face(points, P, { tone = "hi", crease = false, edge = true, cls = "", fill } = {}) {
  const pts = points.map((p) => k.iso(p, P));
  const d = k.pathOf(pts, true);
  const n = G.cross3(G.sub3(points[1], points[0]), G.sub3(points[2], points[0]));
  const nz = G.unit3(n);
  const up = Math.abs(nz[2]) > 0.92;
  const shade = Math.max(0, Math.min(3, G.toneOf(nz[2] < 0 && up ? G.mul3(nz, -1) : nz, P)));
  const body = fill
    ? `<path class="iso-fill" style="fill:${fill}" d="${d}"/>`
    : up
      ? `<path class="iso-fill" d="${d}"/><path class="iso-top" d="${d}"/>`
      : `<path class="iso-fill" d="${d}"/><path class="iso-shade" data-shade="${shade}" d="${d}"/>`;
  const line = edge ? `<path class="iso-line iso-edge" data-tone="${tone}" d="${d}"/>` : "";
  return `<g class="iso-solid${cls ? " " + cls : ""}">${body}${line}</g>`;
}

/** A dark opening (slot, port, bore) drawn on a face. */
export function hole(points, P, { tone = "lo" } = {}) {
  const d = k.pathOf(points.map((p) => k.iso(p, P)), true);
  return `<path class="anat-void" d="${d}"/><path class="iso-line" data-tone="${tone}" d="${d}"/>`;
}

/** Rounded rectangle on a vertical face, as 3D points. axis: the face's in-plane horizontal axis. */
export function roundRect3(c, w, h, r, axis, steps = 4) {
  const pts = [];
  const corners = [
    [w / 2 - r, h / 2 - r, 0],
    [-w / 2 + r, h / 2 - r, Math.PI / 2],
    [-w / 2 + r, -h / 2 + r, Math.PI],
    [w / 2 - r, -h / 2 + r, (3 * Math.PI) / 2],
  ];
  for (const [cu, cv, a0] of corners) {
    for (let i = 0; i <= steps; i++) {
      const a = a0 + (i / steps) * (Math.PI / 2);
      const u = cu + Math.cos(a) * r;
      const v = cv + Math.sin(a) * r;
      pts.push(axis === "x" ? [c[0] + u, c[1], c[2] + v] : [c[0], c[1] + u, c[2] + v]);
    }
  }
  return pts;
}

export const S = (paths, style) => k.solidSvg(paths, style);
export const L = (d, style) => k.lineSvg(d, style);
export const D = (points, style) => k.dotsSvg(points, style);

/** Screw head on a top face: ring + slot + dot. */
export function screwTop(x, y, z, P, r = 1.8) {
  return L(k.ring(x, y, r, z, P, 14), { tone: "mid" }) + L(k.lineOnTop([x - r * 0.6, y - r * 0.3], [x + r * 0.6, y + r * 0.3], z, P), { tone: "lo" });
}

/** Screw head on a vertical face (axis "x" = face normal +y, "y" = face normal +x). */
export function screwSide(c, P, normal, r = 1.6) {
  const F = G.frameAlong(c, normal);
  return `<path class="anat-screw" d="${G.circleOf(F, 0, r, P, 16)}"/>` + L(k.pathOf([G.pointOf(F, 0, r * 0.7, 0.6), G.pointOf(F, 0, r * 0.7, 0.6 + Math.PI)].map((p) => k.iso(p, P))), { tone: "lo" });
}

export function writeArt(file, name, data) {
  const lines = [`// Generated by scripts/anatomy/build-frontends.mjs (${name}). Do not edit by hand.`, ""];
  for (const [key, value] of Object.entries(data)) {
    lines.push(`export const ${key} = ${JSON.stringify(value)} as const;`);
  }
  writeFileSync(file, lines.join("\n") + "\n");
  const size = Buffer.byteLength(lines.join("\n"));
  console.log(`wrote ${file} (${(size / 1024).toFixed(1)} KB)`);
}
